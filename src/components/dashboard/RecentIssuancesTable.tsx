import React from 'react';
import { Link } from 'react-router-dom';
import { Certificate } from '../../types/certificate';
import { Badge } from '../ui/Badge';
import { formatDate } from '../../utils/dateUtils';
import { ArrowRight, ExternalLink } from 'lucide-react';
import { Card, CardHeader } from '../ui/Card';

interface RecentIssuancesTableProps {
  certificates: Certificate[];
}

export const RecentIssuancesTable: React.FC<RecentIssuancesTableProps> = ({ certificates }) => {
  const recent = certificates.slice(0, 5);

  return (
    <Card>
      <CardHeader
        title="Recent Certificate Issuances"
        subtitle="Latest credentials generated by your institution"
        action={
          <Link
            to="/institution/certificates"
            className="text-xs font-semibold text-blue-600 hover:text-blue-800 flex items-center gap-1"
          >
            <span>View All</span>
            <ArrowRight size={14} />
          </Link>
        }
      />
      <div className="overflow-x-auto">
        <table className="min-w-full divide-y divide-slate-200 text-left text-xs">
          <thead className="bg-slate-50 text-slate-500 uppercase tracking-wider font-semibold">
            <tr>
              <th scope="col" className="px-5 py-3">Certificate ID</th>
              <th scope="col" className="px-5 py-3">Candidate / Holder</th>
              <th scope="col" className="px-5 py-3">Credential Title</th>
              <th scope="col" className="px-5 py-3">Issue Date</th>
              <th scope="col" className="px-5 py-3">Status</th>
              <th scope="col" className="px-5 py-3 text-right">Action</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-100 bg-white">
            {recent.length === 0 ? (
              <tr>
                <td colSpan={6} className="px-5 py-6 text-center text-slate-400">
                  No certificate issuances found.
                </td>
              </tr>
            ) : (
              recent.map((cert) => (
                <tr key={cert.id} className="hover:bg-slate-50/70 transition-colors">
                  <td className="px-5 py-3.5 font-mono font-semibold text-slate-900">
                    <Link
                      to={`/institution/certificates/${cert.id}`}
                      className="hover:text-blue-600 hover:underline"
                    >
                      {cert.id}
                    </Link>
                  </td>
                  <td className="px-5 py-3.5">
                    <div className="font-medium text-slate-900">{cert.holderName}</div>
                    <div className="text-[11px] text-slate-400">{cert.holderEmail}</div>
                  </td>
                  <td className="px-5 py-3.5">
                    <div className="text-slate-800 truncate max-w-xs">{cert.title}</div>
                    <div className="text-[10px] text-slate-400">{cert.type}</div>
                  </td>
                  <td className="px-5 py-3.5 text-slate-600 whitespace-nowrap">
                    {formatDate(cert.issueDate)}
                  </td>
                  <td className="px-5 py-3.5 whitespace-nowrap">
                    <Badge status={cert.status} size="sm" />
                  </td>
                  <td className="px-5 py-3.5 text-right whitespace-nowrap">
                    <Link
                      to={`/institution/certificates/${cert.id}`}
                      className="text-blue-600 hover:text-blue-800 font-medium inline-flex items-center gap-1"
                    >
                      <span>Manage</span>
                      <ExternalLink size={12} />
                    </Link>
                  </td>
                </tr>
              ))
            )}
          </tbody>
        </table>
      </div>
    </Card>
  );
};
